from __future__ import annotations

import pytest
from PIL import Image

from app.services.image_gen import (
    BrandSpec,
    ImageGenerationError,
    generate_linkedin_image,
)


def brand(**overrides):
    defaults = dict(brand_name="Acme", footer="Generated by LearnToPost AI", color_primary="#123456", color_secondary="#654321", color_text="#FFFFFF")
    defaults.update(overrides)
    return BrandSpec(**defaults)


def test_generates_a_1200x1200_png(tmp_path):
    out = tmp_path / "card.png"
    path = generate_linkedin_image(headline="A normal headline", takeaways=["Point one", "Point two"], brand=brand(), out_path=out)
    img = Image.open(path)
    assert img.size == (1200, 1200)
    assert img.format == "PNG"


def test_minimal_template_also_renders(tmp_path):
    out = tmp_path / "card.png"
    path = generate_linkedin_image(headline="Minimal headline", takeaways=["One point"], brand=brand(template="minimal"), out_path=out)
    assert Image.open(path).size == (1200, 1200)


def test_long_headline_wraps_instead_of_overflowing(tmp_path):
    out = tmp_path / "card.png"
    headline = " ".join(["word"] * 40)  # many real words -> wraps to several lines, still fits
    path = generate_linkedin_image(headline=headline, takeaways=[], brand=brand(), out_path=out)
    assert Image.open(path).size == (1200, 1200)  # did not raise


def test_content_that_cannot_fit_raises_instead_of_overlapping(tmp_path):
    out = tmp_path / "card.png"
    # An unbreakable run of characters wider than the image at every allowed font size.
    with pytest.raises(ImageGenerationError):
        generate_linkedin_image(headline="X" * 500, takeaways=[], brand=brand(), out_path=out)


def test_empty_headline_is_rejected(tmp_path):
    with pytest.raises(ImageGenerationError):
        generate_linkedin_image(headline="   ", takeaways=[], brand=brand(), out_path=tmp_path / "x.png")


def test_more_than_three_takeaways_are_capped(tmp_path):
    out = tmp_path / "card.png"
    path = generate_linkedin_image(headline="Headline", takeaways=["1", "2", "3", "4", "5"], brand=brand(), out_path=out)
    assert Image.open(path).size == (1200, 1200)  # does not error on extra items, just caps them
